export const DICT: { sw: Record<Key, string>; en: Record<Key, string> } = { sw, en };

export const MONTHS: Record<Lang, string[]> = {
  sw: ["Januari", "Februari", "Machi", "Aprili", "Mei", "Juni", "Julai", "Agosti", "Septemba", "Oktoba", "Novemba", "Desemba"],
  en: ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"],
};

export type Vars = Record<string, string | number>;

export function tr(lang: Lang, key: Key, vars?: Vars): string {
  const s = DICT[lang][key] ?? DICT.sw[key] ?? key;
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

/** Looks up a key built at runtime (e.g. crop names); undefined when unknown. */
export function trMaybe(lang: Lang, key: string, vars?: Vars): string | undefined {
  return Object.prototype.hasOwnProperty.call(DICT.sw, key) ? tr(lang, key as Key, vars) : undefined;
}
